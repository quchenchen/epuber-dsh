#!/usr/bin/env node
/**
 * 把品牌真源同步到桌面 workspace（`dsh-plugin-desktop`）。
 *
 * **为什么需要这个脚本**：`assets/brand/brand.json` 是机器可读真源，但桌面侧有两处
 * 无法在运行时读它——
 *   1. `package.json` 是静态 JSON，不能执行代码；
 *   2. Electron 主进程代码会被打包进可执行文件，读不到工作树里的 brand.json。
 * 所以名字只能"冻"进这两个地方。本脚本就是那次冻结动作，让「改名」保持为
 * 改真源 + 跑同步，而不是撒网式搜索替换。
 *
 * 同步目标与来源（全部取自 brand.json）：
 *   - `dsh-plugin-desktop/package.json`：description / productName / artifactName×3 /
 *     CFBundleDisplayName / executableName×2 / shortcutName
 *   - `dsh-plugin-desktop/src/brand.generated.ts`：主进程用的名字常量
 *   - `dsh-plugin-desktop/build/assistedMessages.yml`：安装向导文案
 *
 * 用例：
 *   node scripts/sync-brand-to-desktop.mjs          # 写入
 *   node scripts/sync-brand-to-desktop.mjs --check  # 只校验是否已同步，漂移即非 0 退出
 *
 * 目录设计：本脚本属于 web workspace（真源在那里），但写桌面 workspace 的文件。
 * 跨 workspace 写只在**开发期**发生；桌面发布的产物不依赖它。
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = resolve(SCRIPT_DIR, '..');
const REPO_ROOT = resolve(WEB_ROOT, '..');
const DESKTOP_ROOT = join(REPO_ROOT, 'dsh-plugin-desktop');

const BRAND_JSON = join(WEB_ROOT, 'assets', 'brand', 'brand.json');
const DESKTOP_PKG = join(DESKTOP_ROOT, 'package.json');
const BRAND_MODULE = join(DESKTOP_ROOT, 'src', 'brand.generated.ts');
const ASSISTED_MESSAGES = join(DESKTOP_ROOT, 'build', 'assistedMessages.yml');

const checkOnly = process.argv.slice(2).includes('--check');
const rel = (file) => relative(REPO_ROOT, file);

const brand = JSON.parse(readFileSync(BRAND_JSON, 'utf8'));
const NAME_ZH = brand.displayName?.zh;
const NAME_EN = brand.displayName?.en;
const PRODUCT_NAME = brand.desktop?.productName;
const SLUG = brand.desktop?.artifactSlug;
if (typeof NAME_ZH !== 'string' || typeof NAME_EN !== 'string'
  || typeof PRODUCT_NAME !== 'string' || typeof SLUG !== 'string') {
  console.error('[sync-brand] brand.json 缺少 displayName.{zh,en} 或 desktop.{productName,artifactSlug}');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(DESKTOP_PKG, 'utf8'));

/** 预期的 package.json 品牌字段（点路径 → 值）。 */
const expectedPackage = [
  ['description', `${NAME_EN} Electron carrier for a pinned DeepSeek Harness runtime Profile`],
  ['build.productName', PRODUCT_NAME],
  ['build.mac.artifactName', `${SLUG}-\${version}-\${arch}.\${ext}`],
  ['build.mac.extendInfo.CFBundleDisplayName', NAME_ZH],
  ['build.win.artifactName', `${SLUG}-\${version}-\${arch}-Portable.\${ext}`],
  ['build.win.executableName', SLUG],
  ['build.nsis.artifactName', `${SLUG}-\${version}-\${arch}-Setup.\${ext}`],
  ['build.nsis.shortcutName', NAME_ZH],
  ['build.linux.executableName', SLUG],
];

const readField = (path) => path.split('.').reduce((value, key) => value?.[key], manifest);
const writeField = (path, value) => {
  const keys = path.split('.');
  let target = manifest;
  for (const key of keys.slice(0, -1)) {
    if (typeof target[key] !== 'object' || target[key] === null) target[key] = {};
    target = target[key];
  }
  target[keys.at(-1)] = value;
};

const drift = [];
for (const [path, wanted] of expectedPackage) {
  const current = readField(path);
  if (current !== wanted) {
    drift.push(`${rel(DESKTOP_PKG)} → ${path}: ${JSON.stringify(current)} → ${JSON.stringify(wanted)}`);
    writeField(path, wanted);
  }
}

/** 主进程名字常量模块。 */
const brandModule = `// AUTO-GENERATED by workdsh-web/scripts/sync-brand-to-desktop.mjs — 请勿手改。
//
// 桌面侧品牌名的唯一定义点。Electron 主进程无法在运行时读
// workdsh-web/assets/brand/brand.json（package.json 是静态 JSON，主进程代码会被
// 打包进可执行文件），所以由同步脚本把名字冻成常量。
// 改名：改品牌真源 → 重跑同步；不要手改本文件。

/** 应用显示名：菜单栏、窗口标题、Dock。 */
export const BRAND_DISPLAY_NAME = '${NAME_ZH}'

/** 应用英文名：英文安装文案与副标。 */
export const BRAND_DISPLAY_NAME_EN = '${NAME_EN}'
`;

/** 安装向导文案。键名与句式沿用上游模板，只把品牌名换成真源值。 */
const assistedMessages = `# AUTO-GENERATED by workdsh-web/scripts/sync-brand-to-desktop.mjs — 请勿手改。
installing:
  en: "Installing ${NAME_EN}. This may take several minutes; please keep this window open."
  zh_CN: "${NAME_ZH} 正在安装，可能需要几分钟；请保持此窗口打开。"
  zh_TW: "${NAME_ZH} 正在安裝，可能需要幾分鐘；請保持此視窗開啟。"
`;

/** 读取现有文本；不存在返回 undefined。 */
function readIfPresent(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return undefined;
  }
}

for (const [file, wanted, label] of [
  [BRAND_MODULE, brandModule, '主进程名字常量'],
  [ASSISTED_MESSAGES, assistedMessages, '安装向导文案'],
]) {
  if (readIfPresent(file) !== wanted) drift.push(`${rel(file)} → ${label} 与真源不一致`);
}

if (drift.length === 0) {
  console.log(`[sync-brand] 已与真源一致（${NAME_ZH} / ${SLUG}），无需改动。`);
  process.exit(0);
}

if (checkOnly) {
  console.error(`\x1b[31m[sync-brand] 桌面 workspace 与品牌真源不一致：${drift.length} 处\x1b[0m`);
  for (const item of drift) console.error(`  - ${item}`);
  console.error('\n  运行 `node scripts/sync-brand-to-desktop.mjs` 同步。');
  process.exit(1);
}

writeFileSync(DESKTOP_PKG, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
writeFileSync(BRAND_MODULE, brandModule, 'utf8');
writeFileSync(ASSISTED_MESSAGES, assistedMessages, 'utf8');

console.log(`[sync-brand] 已同步品牌「${NAME_ZH}」到 ${rel(DESKTOP_ROOT)}：`);
for (const item of drift) console.log(`  ✓ ${item}`);
